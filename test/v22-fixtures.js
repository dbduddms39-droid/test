// - oracle: 기획상 기대 판정 (사람이 작성한 오라클). F06은 동결 v2.2의 정정값을 쓴다.
//   F09~F11은 v2.2.1 사전등록 보완값을 쓰고, 원본 오라클과 다른 칸은 originalOracle에 따로 기록한다.

// 문서와 인용 구절로 AI 응답 형식의 세부기준 항목을 만든다. 구절이 있는 줄 번호는 분할 결과에서 찾는다.
// spec: { f: finding, q: [구절...], sv, term, kind, calc }
export function buildExtraction(segments, specs, criterionIds) {
  const lineOf = (phrase) => {
    const seg = segments.find((s) => s.text.includes(phrase));
    if (!seg) throw new Error(`fixture phrase not found: ${phrase}`);
    return seg.id;
  };
  return {
    criteria: criterionIds.map((id) => {
      const s = specs[id] ?? { f: 'absent' };
      return {
        id,
        finding: s.f,
        quotes: (s.q ?? []).map((text) => ({ line: lineOf(text), text })),
        source_value: s.sv ?? null,
        term_type: s.term ?? null,
        value_kind: s.kind ?? null,
        calc: s.calc ?? null,
      };
    }),
  };
}

