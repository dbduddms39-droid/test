// - text: 가상 문서 원문 (실제 회사·인물과 무관)
// - extraction: 기준표대로 올바르게 동작하는 AI가 돌려줄 추출값을 사람이 작성한 것.
//   즉 이 테스트는 "추출이 올바를 때 서버의 검증·규칙이 기획상 기대 판정을 만드는지"를 본다.
